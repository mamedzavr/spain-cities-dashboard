export function formatMetric(value: number, format?: MetricDef['format']): string {
  switch (format) {
    case 'euro':
      return new Intl.NumberFormat('ru-RU', {
        style: 'currency',
        currency: 'EUR',
        maximumFractionDigits: value >= 100 ? 0 : 2,
      }).format(value)
    case 'percent':
      return `${value.toFixed(value % 1 === 0 ? 0 : 1)}%`
    case 'index':
      return value.toFixed(value < 20 ? 1 : 0)
    default:
      return new Intl.NumberFormat('ru-RU', { maximumFractionDigits: 1 }).format(value)
  }
}

export function affordabilityScore(city: CityStats): number {
  // Higher = more affordable relative to local salary
  const rentShare = city.rent1brCenter / city.salaryNet
  const col = city.costOfLivingIndex / 100
  const raw = 100 - rentShare * 70 - col * 25
  return Math.max(5, Math.min(95, Math.round(raw)))
}

export function overallScore(city: CityStats): number {
  const afford = affordabilityScore(city)
  return Math.round(
    afford * 0.22 +
      city.salaryNet / 25 * 0.12 +
      city.jobMarket * 0.12 +
      city.safetyIndex * 0.1 +
      city.healthcareIndex * 0.08 +
      city.sunnyDays / 3.2 * 0.1 +
      city.walkability * 0.08 +
      city.culture * 0.08 +
      city.beachAccess * 0.05 +
      (100 - city.unemployment * 3) * 0.05,
  )
}
